"""Download and self-host the Google fonts (latin subset only).

Removes the render-blocking fonts.googleapis.com stylesheet and the
third-party connection — a straight LCP win.

Run: python tools/fetch-fonts.py
"""
import hashlib
import os
import re
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "fonts")
CSS_OUT = os.path.join(ROOT, "fonts.css")

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")
URL = ("https://fonts.googleapis.com/css2?"
       "family=Inter:wght@400;500;600;700&family=Rajdhani:wght@500;600;700"
       "&family=Orbitron:wght@700;900&display=swap")

KEEP_SUBSETS = {"latin", "latin-ext"}


def main():
    os.makedirs(FONTS, exist_ok=True)
    req = urllib.request.Request(URL, headers={"User-Agent": UA})
    css = urllib.request.urlopen(req, timeout=45).read().decode("utf-8")

    # split into "/* subset */ @font-face {...}" chunks
    chunks = re.split(r"/\*\s*([a-z0-9-]+)\s*\*/", css)
    out = []
    kept = 0
    seen = {}

    for i in range(1, len(chunks), 2):
        subset = chunks[i]
        block = chunks[i + 1]
        if subset not in KEEP_SUBSETS:
            continue
        m = re.search(r"url\((https://fonts\.gstatic\.com/[^)]+)\)", block)
        if not m:
            continue
        remote = m.group(1)
        fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        wt = re.search(r"font-weight:\s*([^;]+);", block).group(1).strip()
        req = urllib.request.Request(remote, headers={"User-Agent": UA})
        data = urllib.request.urlopen(req, timeout=45).read()

        # variable fonts ship one file for every weight — dedupe by content hash
        digest = hashlib.md5(data).hexdigest()
        if digest in seen:
            fname = seen[digest]
        else:
            fname = f"{fam.lower()}-{wt.replace(' ', '')}-{subset}.woff2"
            with open(os.path.join(FONTS, fname), "wb") as f:
                f.write(data)
            seen[digest] = fname
        block = block.replace(remote, f"fonts/{fname}")
        out.append(block.strip())
        kept += 1

    header = ("/* ===== GK BATTERIES — SELF-HOSTED FONTS (latin + latin-ext) =====\n"
              "   Generated by tools/fetch-fonts.py — do not edit by hand.\n"
              "   Self-hosted to remove the render-blocking Google Fonts request. */\n")
    with open(CSS_OUT, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(out) + "\n")

    # inject the @font-face rules straight into styles.css (one less request)
    css_path = os.path.join(ROOT, "styles.css")
    scss = open(css_path, encoding="utf-8").read()
    o, c = "/* @gen:fonts */", "/* /@gen:fonts */"
    if o in scss and c in scss:
        head, rest = scss.split(o, 1)
        _, tail = rest.split(c, 1)
        scss = head + o + "\n" + "\n".join(out) + "\n" + c + tail
        open(css_path, "w", encoding="utf-8").write(scss)
        print("[fonts] injected @font-face rules into styles.css")

    total = sum(os.path.getsize(os.path.join(FONTS, f)) for f in os.listdir(FONTS))
    print(f"[fonts] {kept} @font-face blocks, {len(os.listdir(FONTS))} files, {total//1024} KB total")
    print(f"[fonts] wrote fonts.css")


if __name__ == "__main__":
    main()
