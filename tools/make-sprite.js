/* ===== GK BATTERIES — ICON SPRITE GENERATOR =====
 * Builds images/icons.svg containing only the icons the site actually uses.
 * This replaces the 454 KB lucide UMD bundle with a ~10 KB sprite.
 *
 * Run:  npm run sprite
 * ====================================================== */

const fs = require('fs');
const path = require('path');
const lucide = require('lucide');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'images', 'icons.svg');

/* kebab-case -> PascalCase (lucide export names) */
const pascal = (kebab) => kebab.split('-')
  .map(part => part.charAt(0).toUpperCase() + part.slice(1))
  .join('');

/* every icon referenced by the site */
const ICONS = [
  'alert-triangle', 'award', 'badge-check', 'battery-charging', 'car', 'check',
  'chevron-down', 'clock', 'hammer', 'handshake', 'history', 'home', 'layers',
  'map-pin', 'messages-square', 'milestone', 'navigation', 'phone', 'phone-call',
  'plug-zap', 'repeat', 'shield-check', 'sprout', 'star', 'store', 'tractor',
  'truck', 'user-round', 'users', 'wrench', 'zap'
];

const ATTR_ORDER = ['d', 'points', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'cx', 'cy',
  'r', 'rx', 'ry', 'width', 'height'];

function nodeToSvg(node) {
  const [tag, attrs] = node;
  const keys = Object.keys(attrs).sort((a, b) => {
    const ia = ATTR_ORDER.indexOf(a), ib = ATTR_ORDER.indexOf(b);
    return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib);
  });
  const attrStr = keys.map(k => `${k}="${String(attrs[k])}"`).join(' ');
  return `<${tag} ${attrStr}/>`;
}

function main() {
  const symbols = [];
  const missing = [];

  ICONS.forEach(name => {
    const key = pascal(name);
    const icon = lucide.icons && lucide.icons[key] ? lucide.icons[key] : lucide[key];
    if (!icon) { missing.push(name + ' (' + key + ')'); return; }
    const inner = icon.map(nodeToSvg).join('');
    symbols.push(
      `  <symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
      `stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`
    );
  });

  if (missing.length) {
    console.error('[sprite] MISSING ICONS: ' + missing.join(', '));
    process.exitCode = 1;
  }

  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- GK Batteries icon sprite — generated by tools/make-sprite.js (npm run sprite) -->
<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">
${symbols.join('\n')}
</svg>
`;
  fs.writeFileSync(OUT, svg, 'utf8');
  console.log('[sprite] wrote images/icons.svg — ' + symbols.length + ' icons, ' +
    Math.round(fs.statSync(OUT).size / 1024) + ' KB');
  if (missing.length) console.error('[sprite] missing: ' + missing.join(', '));
}

main();
